// 把 share-page 的 CSS/JS/config 以 base64 内联进 Edge Function，
// 避免在 TS 模板字符串里转义反引号 / ${}。
// 用法：node scripts/build-share-assets.mjs   （或 pnpm share:assets）
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p)).toString('base64');

const out = `// AUTO-GENERATED by scripts/build-share-assets.mjs — 不要手改
// 重新生成：pnpm share:assets
export const CSS_B64 = '${read('share-page/styles.css')}';
export const JS_B64 = '${read('share-page/snapshot.js')}';
export const CONFIG_B64 = '${read('share-page/config.js')}';
`;

mkdirSync(join(root, 'supabase/functions/share'), { recursive: true });
writeFileSync(join(root, 'supabase/functions/share/assets.ts'), out);
console.log('✓ supabase/functions/share/assets.ts 已生成');
